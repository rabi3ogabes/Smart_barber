// Generates lib/src/tokens/sb_tokens.g.dart from ../../design/tokens.json — the same source
// the dashboard uses (backend/scripts/build-tokens.mjs). Run from packages/sb_ui:
//   dart run tool/generate_tokens.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final root = File.fromUri(Platform.script).parent.parent;
  final source = File('${root.path}/../../design/tokens.json');
  final tokens = jsonDecode(source.readAsStringSync()) as Map<String, dynamic>;
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_tokens.dart from design/tokens.json — do not edit by hand.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln("import 'package:material_ui/material_ui.dart';")
    ..writeln();

  // Colours ---------------------------------------------------------------
  final colors = (tokens['color'] as Map<String, dynamic>).cast<String, Map<String, dynamic>>();
  final names = colors.keys.map(_camel).toList();
  out
    ..writeln('/// Colour tokens for one brightness. Read with `context.sbColors`.')
    ..writeln('@immutable')
    ..writeln('class SbColors extends ThemeExtension<SbColors> {')
    ..writeln('  const SbColors({')
    ..writeAll(names.map((n) => '    required this.$n,\n'))
    ..writeln('  });')
    ..writeln()
    ..writeAll(names.map((n) => '  final Color $n;\n'))
    ..writeln()
    ..writeln('  static const SbColors light = SbColors(')
    ..writeAll(colors.entries.map((e) => '    ${_camel(e.key)}: ${_color(e.value['light'] as String)},\n'))
    ..writeln('  );')
    ..writeln()
    ..writeln('  static const SbColors dark = SbColors(')
    ..writeAll(colors.entries.map((e) => '    ${_camel(e.key)}: ${_color(e.value['dark'] as String)},\n'))
    ..writeln('  );')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  SbColors copyWith({${names.map((n) => 'Color? $n').join(', ')}}) => SbColors(')
    ..writeAll(names.map((n) => '        $n: $n ?? this.$n,\n'))
    ..writeln('      );')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  SbColors lerp(ThemeExtension<SbColors>? other, double t) {')
    ..writeln('    if (other is! SbColors) return this;')
    ..writeln('    return SbColors(')
    ..writeAll(names.map((n) => '      $n: Color.lerp($n, other.$n, t)!,\n'))
    ..writeln('    );')
    ..writeln('  }')
    ..writeln('}')
    ..writeln();

  // Type scale ------------------------------------------------------------
  final type = (tokens['type'] as Map<String, dynamic>).cast<String, Map<String, dynamic>>();
  out
    ..writeln('/// Type scale (logical pixels). Weight is applied as both FontWeight and the variable-font axis.')
    ..writeln('@immutable')
    ..writeln('class SbTypeToken {')
    ..writeln('  const SbTypeToken({required this.size, required this.lineHeight, required this.weight});')
    ..writeln('  final double size;')
    ..writeln('  final double lineHeight;')
    ..writeln('  final int weight;')
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class SbType {')
    ..writeAll(type.entries.map((e) => '  static const ${_camel(e.key)} = SbTypeToken(size: ${e.value['size']}, lineHeight: ${e.value['line']}, weight: ${e.value['weight']});\n'))
    ..writeln('}')
    ..writeln();

  // Radius, spacing, motion, layout --------------------------------------
  final radius = tokens['radius'] as Map<String, dynamic>;
  out
    ..writeln('abstract final class SbRadius {')
    ..writeAll(radius.entries.map((e) => '  static const double ${_camel(e.key)} = ${(e.value as num).toDouble()};\n'))
    ..writeln('}')
    ..writeln();

  final spacing = (tokens['spacing'] as List).cast<num>();
  const spacingNames = ['xxs', 'xs', 'sm', 'md', 'lg', 'xl', 'xxl'];
  out
    ..writeln('/// Spacing scale ${spacing.join('-')}.')
    ..writeln('abstract final class SbSpace {')
    ..writeAll([for (var i = 0; i < spacing.length; i++) '  static const double ${spacingNames[i]} = ${spacing[i].toDouble()};\n'])
    ..writeln('}')
    ..writeln();

  final motion = tokens['motion'] as Map<String, dynamic>;
  final easing = RegExp(r'cubic-bezier\(([^)]+)\)').firstMatch(motion['easing'] as String)!.group(1)!.split(',').map((s) => double.parse(s.trim()));
  out
    ..writeln('abstract final class SbMotion {')
    ..writeln('  static const fast = Duration(milliseconds: ${motion['fast']});')
    ..writeln('  static const base = Duration(milliseconds: ${motion['base']});')
    ..writeln('  static const slow = Duration(milliseconds: ${motion['slow']});')
    ..writeln('  static const curve = Cubic(${easing.join(', ')});')
    ..writeln('}')
    ..writeln();

  final layout = tokens['layout'] as Map<String, dynamic>;
  out
    ..writeln('abstract final class SbLayout {')
    ..writeAll(layout.entries.map((e) => '  static const double ${_camel(e.key)} = ${(e.value as num).toDouble()};\n'))
    ..writeln('}')
    ..writeln();

  final fonts = tokens['font'] as Map<String, dynamic>;
  out
    ..writeln('abstract final class SbFonts {')
    ..writeln("  static const sansLatin = '${fonts['sans-latin']}';")
    ..writeln("  static const displayLatin = '${fonts['display-latin']}';")
    ..writeln("  static const sansArabic = '${fonts['sans-arabic']}';")
    ..writeln('}');

  final target = File('${root.path}/lib/src/tokens/sb_tokens.g.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${target.path}');
}

String _camel(String key) {
  final parts = key.split('-');
  return parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

String _color(String value) {
  final hex = RegExp(r'^#([0-9a-fA-F]{6})$').firstMatch(value);
  if (hex != null) return 'Color(0xFF${hex.group(1)!.toUpperCase()})';
  final rgba = RegExp(r'^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$').firstMatch(value);
  if (rgba != null) {
    final a = (double.parse(rgba.group(4)!) * 255).round();
    String h(int v) => v.toRadixString(16).padLeft(2, '0').toUpperCase();
    return 'Color(0x${h(a)}${h(int.parse(rgba.group(1)!))}${h(int.parse(rgba.group(2)!))}${h(int.parse(rgba.group(3)!))})';
  }
  throw FormatException('Unsupported colour $value');
}
