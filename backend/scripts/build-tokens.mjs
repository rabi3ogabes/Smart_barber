// Generates resources/css/tokens.css from ../design/tokens.json (single source of truth).
// Run automatically before `npm run build` and `npm run dev`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(resolve(here, '../../design/tokens.json'), 'utf8'));

const light = [];
const dark = [];
const theme = [];

for (const [name, value] of Object.entries(tokens.color)) {
    light.push(`  --sb-${name}: ${value.light};`);
    dark.push(`  --sb-${name}: ${value.dark};`);
    theme.push(`  --color-${name}: var(--sb-${name});`);
}
for (const [name, value] of Object.entries(tokens.shadow)) {
    light.push(`  --sb-shadow-${name}: ${value.light};`);
    dark.push(`  --sb-shadow-${name}: ${value.dark};`);
    theme.push(`  --shadow-${name}: var(--sb-shadow-${name});`);
}
for (const [name, t] of Object.entries(tokens.type)) {
    theme.push(`  --text-${name}: ${t.size / 16}rem;`);
    theme.push(`  --text-${name}--line-height: ${t.line / 16}rem;`);
    theme.push(`  --text-${name}--font-weight: ${t.weight};`);
}
for (const [name, px] of Object.entries(tokens.radius)) {
    theme.push(`  --radius-${name}: ${px === 999 ? '9999px' : `${px / 16}rem`};`);
}
for (const [name, ms] of Object.entries(tokens.motion)) {
    theme.push(name === 'easing' ? `  --ease-sb: ${ms};` : `  --duration-${name}: ${ms}ms;`);
}
for (const [name, px] of Object.entries(tokens.layout)) {
    light.push(`  --sb-${name}: ${px / 16}rem;`);
}

const f = tokens.font;
theme.push(`  --font-sans: '${f['sans-latin']}', '${f['sans-arabic']}', ui-sans-serif, system-ui, sans-serif;`);
theme.push(`  --font-arabic: '${f['sans-arabic']}', '${f['sans-latin']}', ui-sans-serif, system-ui, sans-serif;`);
theme.push(`  --font-display: '${f['display-latin']}', ui-serif, Georgia, serif;`);

const css = `/* GENERATED by scripts/build-tokens.mjs from design/tokens.json — do not edit by hand. */
:root {
${light.join('\n')}
  color-scheme: light;
}

:root.dark {
${dark.join('\n')}
  color-scheme: dark;
}

@theme inline {
${theme.join('\n')}
}
`;

writeFileSync(resolve(here, '../resources/css/tokens.css'), css);
console.log('tokens.css generated');
